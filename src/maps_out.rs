//! Human `library.md` and sharded folder cards written by `update-maps`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use crate::cache;
use crate::jsonutil::Json;

const MERMAID_CAP: usize = 80;

pub fn write(root: &Path) -> Result<(), String> {
    let paths = cache::all_paths(root);
    let mut edges: Vec<(String, String)> = Vec::new();
    let mut flagged = 0i64;
    for src in &paths {
        let view = cache::load_dependency_view(root, src).map_err(|e| e.to_string())?;
        for edge in view.internal {
            if edge.conditional || edge.dynamic || edge.via_barrel || edge.confidence() < 0.8 {
                flagged += 1;
            }
            edges.push((src.clone(), edge.path));
        }
    }
    edges.sort();
    edges.dedup();
    write_library(root, &paths, &edges, flagged)?;
    write_cards(root, &paths)?;
    Ok(())
}

fn write_library(root: &Path, paths: &[String], edges: &[(String, String)], flagged: i64) -> Result<(), String> {
    let mut md = String::from("# Library\n\nGenerated by `wikifier update-maps`. Agents orient with the root folder card and `list-paths`, not this mermaid.\n\n");
    md.push_str(&format!("Files: {}. Edges: {}.\n\n", paths.len(), edges.len()));
    md.push_str("## File Tree\n\n```text\n");
    for path in paths {
        md.push_str(path);
        md.push('\n');
    }
    md.push_str("```\n\n");
    md.push_str("## Dependencies\n\n```mermaid\nflowchart LR\n");
    let shown = edges.len().min(MERMAID_CAP);
    let mut ids: BTreeMap<String, usize> = BTreeMap::new();
    for (src, dst) in edges.iter().take(shown) {
        let s = node_id(&mut ids, src);
        let d = node_id(&mut ids, dst);
        md.push_str(&format!("  n{s}[\"{}\"] --> n{d}[\"{}\"]\n", esc(src), esc(dst)));
    }
    md.push_str("```\n\n");
    if edges.len() > MERMAID_CAP {
        md.push_str(&format!("Mermaid shows the first {MERMAID_CAP} edges of {}.\n\n", edges.len()));
    }
    md.push_str("| Source | Depends on |\n|--------|------------|\n");
    let mut by_src: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (src, dst) in edges {
        by_src.entry(src.as_str()).or_default().push(dst.as_str());
    }
    for (src, dsts) in &by_src {
        md.push_str(&format!("| {src} | {} |\n", dsts.join(", ")));
    }
    md.push_str(&format!("\nEdges with a conditional, dynamic, barrel, or lower-confidence flag: {flagged}.\n"));
    md.push_str("Run `wikifier cycles` for a break hint on each strongly connected component.\n");
    fs::write(root.join("library.md"), md).map_err(|e| e.to_string())
}

fn node_id(ids: &mut BTreeMap<String, usize>, path: &str) -> usize {
    if let Some(id) = ids.get(path) {
        return *id;
    }
    let id = ids.len();
    ids.insert(path.to_string(), id);
    id
}

fn esc(path: &str) -> String {
    path.replace('"', "'")
}

fn write_cards(root: &Path, paths: &[String]) -> Result<(), String> {
    let maps = root.join(".wikifier_staging").join("maps");
    if maps.is_dir() {
        let _ = fs::remove_dir_all(&maps);
    }
    let mut prefixes: BTreeSet<String> = BTreeSet::new();
    prefixes.insert(String::new());
    for path in paths {
        let mut acc = String::new();
        if let Some((dir, _)) = path.rsplit_once('/') {
            for part in dir.split('/') {
                if !acc.is_empty() {
                    acc.push('/');
                }
                acc.push_str(part);
                prefixes.insert(acc.clone());
            }
        }
    }
    for prefix in prefixes {
        let card = folder_json(&prefix, paths);
        let path = if prefix.is_empty() {
            maps.join("_root.json")
        } else {
            maps.join(&prefix).join("_index.json")
        };
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(path, card.to_string()).map_err(|e| e.to_string())?;
    }
    Ok(())
}

fn folder_json(prefix: &str, paths: &[String]) -> Json {
    let pref = prefix.trim_matches('/');
    let mut direct = Vec::new();
    let mut dirs: BTreeMap<String, i64> = BTreeMap::new();
    for path in paths {
        let rest = if pref.is_empty() {
            path.as_str()
        } else if let Some(rest) = path.strip_prefix(&(pref.to_string() + "/")) {
            rest
        } else {
            continue;
        };
        if rest.is_empty() {
            continue;
        }
        if let Some((dir, _)) = rest.split_once('/') {
            *dirs.entry(format!("{dir}/")).or_insert(0) += 1;
        } else {
            direct.push(path.clone());
        }
    }
    direct.sort();
    Json::obj(vec![
        ("prefix", Json::String(pref.into())),
        ("files", Json::Array(direct.iter().cloned().map(Json::String).collect())),
        ("dirs", Json::Array(dirs.into_iter().map(|(p, n)| Json::obj(vec![("p", Json::String(p)), ("n", Json::Int(n))])).collect())),
        ("file_count", Json::Int(paths.iter().filter(|p| pref.is_empty() || p.as_str() == pref || p.starts_with(&(pref.to_string() + "/"))).count() as i64)),
    ])
}

pub fn write_status(root: &Path, body: &Json) -> Result<(), String> {
    let staging = root.join(".wikifier_staging");
    fs::create_dir_all(&staging).map_err(|e| e.to_string())?;
    fs::write(staging.join("incremental_status.json"), body.to_string()).map_err(|e| e.to_string())
}

pub fn read_status(root: &Path) -> Json {
    let path = root.join(".wikifier_staging").join("incremental_status.json");
    fs::read_to_string(path).ok().and_then(|text| crate::jsonutil::parse(&text).ok()).unwrap_or(Json::obj(vec![]))
}
